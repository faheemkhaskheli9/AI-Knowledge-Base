"""Regenerate INDEX.md from the frontmatter of every topic file.

Run after adding or editing a topic:  python build_index.py
Stdlib only; parses the simple frontmatter shape used in _template.md.
"""
import re
from pathlib import Path

ROOT = Path(__file__).parent
SKIP = {"README.md", "AGENTS.md", "CLAUDE.md", "INDEX.md", "_template.md"}


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---", text.replace("\r\n", "\n"), re.S)
    if not m:
        return None
    meta, key = {}, None
    for line in m.group(1).splitlines():
        if line.startswith("  - ") and key:
            meta.setdefault(key, []).append(line[4:].strip().strip('"'))
        elif ":" in line and not line.startswith(" "):
            key, _, val = line.partition(":")
            key, val = key.strip(), val.split("#")[0].strip()
            if val.startswith("["):
                meta[key] = [v.strip() for v in val.strip("[]").split(",") if v.strip()]
            elif val:
                meta[key] = val.strip('"')
    return meta


def build():
    rows, bad = [], []
    for path in sorted(ROOT.rglob("*.md")):
        rel = path.relative_to(ROOT).as_posix()
        if path.name in SKIP or rel.startswith("."):
            continue
        meta = frontmatter(path.read_text(encoding="utf-8"))
        if not meta or "title" not in meta:
            bad.append(rel)
            continue
        uses = meta.get("use_cases", [])
        rows.append(
            f"| [{meta['title']}]({rel}) | {meta.get('category', rel.split('/')[0])} "
            f"| {', '.join(meta.get('tags', []))} | {'; '.join(uses[:3])} "
            f"| {meta.get('status', '?')} |"
        )
    out = [
        "# Index",
        "",
        "Generated by `python build_index.py` - do not edit by hand.",
        f"{len(rows)} topics. Match your task against Tags / Use when, then read the full file.",
        "",
        "| Topic | Category | Tags | Use when | Status |",
        "|---|---|---|---|---|",
        *rows,
        "",
    ]
    (ROOT / "INDEX.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    return rows, bad


if __name__ == "__main__":
    rows, bad = build()
    print(f"indexed {len(rows)} topics")
    if bad:
        raise SystemExit(f"missing/invalid frontmatter: {bad}")
